/**
 * Regenerate the baseline migration from the current schema.
 *
 *   npm run db:migrations:build
 *
 * The migration targets POSTGRES (the deployment provider) regardless of what the local
 * schema is currently flipped to, so a developer working on SQLite can still produce a
 * correct production migration. The local schema file is never modified.
 */
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync, rmSync, mkdirSync } from "node:fs"

const SCHEMA = "prisma/schema.prisma"
const OUT_DIR = "prisma/migrations/0_init"
const TMP = "prisma/.build-pg.prisma"

const schema = readFileSync(SCHEMA, "utf8")
writeFileSync(TMP, schema.replace(/provider = "(sqlite|postgresql)"/, 'provider = "postgresql"'))
try {
  const sql = execFileSync("npx",
    ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", TMP, "--script"],
    { encoding: "utf8", shell: process.platform === "win32" })
  mkdirSync(OUT_DIR, { recursive: true })
  writeFileSync(`${OUT_DIR}/migration.sql`, sql)
  // Prisma refuses to read a migrations directory without the connector lock.
  writeFileSync(
    "prisma/migrations/migration_lock.toml",
    [
      "# Please do not edit this file manually",
      "# It should be added in your version-control system (e.g. Git)",
      'provider = "postgresql"',
      "",
    ].join("\n"),
  )
  const tables = (sql.match(/CREATE TABLE/g) || []).length
  const idx = (sql.match(/CREATE (UNIQUE )?INDEX/g) || []).length
  const fks = (sql.match(/FOREIGN KEY/g) || []).length
  console.log(`Wrote ${OUT_DIR}/migration.sql — ${tables} tables, ${idx} indexes, ${fks} foreign keys.`)
} finally {
  rmSync(TMP, { force: true })
}
